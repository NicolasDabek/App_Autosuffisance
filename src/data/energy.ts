export function steresForHeat(kwhHeat: number, insulation: string, climateHeatFactor: number) {
  const insul =
    insulation === "passive" ? 0.45 : insulation === "bonne" ? 0.7 : insulation === "moyenne" ? 1 : 1.25;
  const need = kwhHeat * insul * climateHeatFactor;
  const kwhPerStere = 1750;
  return need / kwhPerStere;
}

export function pvYield(roofM2: number, kwhPerKwc: number) {
  const kwc = roofM2 * 0.18; // ~180 W/m² modules
  return { kwc, kwh: kwc * kwhPerKwc };
}
